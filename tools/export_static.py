#!/usr/bin/env python3
"""Build a static, backend-free preview of the frontend into dist/.

Used by the GitHub Pages workflow: the site is the real frontend with a demo
flag set, reading a generated catalog.json and keeping all changes in memory.

    python3 sync.py                 # fill data/app.db + data/images first
    python3 tools/export_static.py  # -> dist/
"""

import json
import math
import shutil
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import sync  # noqa: E402  (for the version + db path)

DATA = ROOT / "data"
DIST = ROOT / "dist"
DB_PATH = DATA / "app.db"


def stats_from_samples(samples):
    """Same definition as server.py: sample sd, None when n < 2."""
    n = len(samples)
    if n == 0:
        return None
    mean = sum(samples) / n
    var = sum((x - mean) ** 2 for x in samples) / (n - 1) if n > 1 else None
    return {
        "n": n,
        "mean": round(mean, 6),
        "sd": round(math.sqrt(var), 6) if var is not None else None,
    }


def build_catalog():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    rows = conn.execute("SELECT * FROM catalog ORDER BY series_order").fetchall()
    meta = {r["key"]: r["value"] for r in conn.execute("SELECT * FROM meta")}
    conn.close()
    if not rows:
        raise SystemExit("catalog is empty — run `python3 sync.py` first")

    figures = []
    for r in rows:
        boxed = stats_from_samples(json.loads(r["samples_boxed"] or "[]"))
        unboxed = stats_from_samples(json.loads(r["samples_unboxed"] or "[]"))
        figures.append(
            {
                "key": r["key"],
                "series": r["series"],
                "name": r["name"],
                "is_secret": bool(r["is_secret"]),
                "avg_boxed": r["avg_boxed"],
                "n_boxed": r["n_boxed"],
                "avg_unboxed": r["avg_unboxed"],
                "n_unboxed": r["n_unboxed"],
                "image": r["image"],
                "tip": r["tip"],
                "stats_boxed": boxed,
                "stats_unboxed": unboxed,
            }
        )

    out_meta = {
        "version": sync.read_version(),
        "sheet_updated": meta.get("sheet_updated", ""),
        "figure_count": meta.get("figure_count", str(len(figures))),
        "series_count": meta.get("series_count", ""),
        "packaging": json.loads(meta.get("packaging") or "{}"),
        "demo": True,
    }
    return {"figures": figures, "meta": out_meta}


def main():
    catalog = build_catalog()
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)

    # frontend, verbatim
    shutil.copytree(ROOT / "static", DIST / "static")

    # figure photos (generated by sync.py, not tracked in git)
    src_images = DATA / "images"
    if not src_images.exists() or not any(src_images.iterdir()):
        raise SystemExit("no images in data/images — run `python3 sync.py` first")
    shutil.copytree(src_images, DIST / "images")

    # demo data
    (DIST / "demo").mkdir()
    (DIST / "demo" / "catalog.json").write_text(
        json.dumps(catalog, separators=(",", ":"))
    )

    # index.html with the demo flag injected, plus Pages' no-Jekyll marker
    index = (ROOT / "static" / "index.html").read_text()
    index = index.replace(
        '<script type="module" src="static/app.js"></script>',
        '<script>window.SMISKI_DEMO = true;</script>\n'
        '  <script type="module" src="static/app.js"></script>',
    )
    (DIST / "index.html").write_text(index)
    (DIST / ".nojekyll").write_text("")

    total = sum(f.stat().st_size for f in DIST.rglob("*") if f.is_file())
    print(
        f"dist/ built: {len(catalog['figures'])} figures, "
        f"{len(list((DIST / 'images').iterdir()))} images, {total / 1e6:.1f} MB"
    )


if __name__ == "__main__":
    main()
